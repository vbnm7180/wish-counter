//! `infrastructure` и передаются сюда снаружи. Поэтому логику легко
//! тестировать с подменёнными (fake) хранилищами.
//!
//! Модули:
//! - [`ports`] — интерфейсы, которые должна реализовать инфраструктура;
//! - [`services`] — сервисы со сценариями использования.

