//! Интерфейс хранилища пользовательских настроек.

use domain::settings::AppSettings;
use thiserror::Error;

/// Ошибка хранилища, общая для всех реализаций.
///
/// Реализация (файл, база данных) превращает свои внутренние ошибки
/// в этот тип, чтобы слой приложения не зависел от деталей хранения.
#[derive(Debug, Error)]
pub enum RepositoryError {
    /// Не удалось прочитать или записать данные (диск, права доступа и т.п.).
    #[error("ошибка ввода-вывода хранилища: {0}")]
    Io(String),
    /// Данные прочитаны, но имеют неверный формат.
    #[error("повреждённые данные в хранилище: {0}")]
    Corrupted(String),
}

/// Хранилище пользовательских настроек.
pub trait SettingsRepository: Send + Sync {
    /// Загружает сохранённые настройки.
    ///
    /// Возвращает `Ok(None)`, если настройки ещё ни разу не сохранялись.
    fn load(&self) -> Result<Option<AppSettings>, RepositoryError>;

    /// Сохраняет настройки, полностью заменяя предыдущие.
    fn save(&self, settings: &AppSettings) -> Result<(), RepositoryError>;
}
