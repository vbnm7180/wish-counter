//! Проверка «предмет с баннера или нет» — нужна для подсчёта 50/50.

use crate::wish::Wish;

/// Определяет, был ли выпавший 5★ предметом с баннера (rate-up, featured).
///
/// Для ответа нужно знать, какие персонажи были на каждом баннере и
/// когда. Эти данные появятся на этапе 4 (справочники), а расчёт уже
/// работает через этот интерфейс (принцип инверсии зависимостей).
pub trait FeaturedLookup: Send + Sync {
    /// Возвращает:
    /// - `Some(true)` — предмет был на баннере (50/50 выиграно);
    /// - `Some(false)` — предмет не с баннера (50/50 проиграно);
    /// - `None` — данных о баннере нет, ответить нельзя.
    fn is_featured(&self, wish: &Wish) -> Option<bool>;
}

/// Заглушка, у которой нет данных о баннерах: всегда отвечает `None`.
///
/// Используется, пока справочники не подключены (до этапа 4).
/// Статус 50/50 при этом показывается как «неизвестен».
#[derive(Debug, Default, Clone, Copy)]
pub struct NoFeaturedData;

impl FeaturedLookup for NoFeaturedData {
    /// Всегда `None`: данных нет.
    fn is_featured(&self, _wish: &Wish) -> Option<bool> {
        None
    }
}
