//! # Доменный слой Wish Counter
//!
//! Здесь описаны **сущности** (что такое «игра», «настройки» и т.д.)
//! и **правила** предметной области. Этот крейт — центр архитектуры:
//! от него зависят все остальные, а сам он не знает ни о базе данных,
//! ни об интерфейсе, ни о сети (принцип инверсии зависимостей, буква D в SOLID).
//!
//! Модули:
//! - [`game`] — идентификатор игры, описание игры и интерфейс игрового модуля;
//! - [`settings`] — пользовательские настройки (тема, язык);
//! - [`wish`] — молитва: предмет, редкость, баннер, время;
//! - [`pity`] — правила гаранта, расчёт счётчиков и статуса 50/50.

